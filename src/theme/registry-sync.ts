/**
 * The preset registry (`presets/_registry.ts`) is generated from the files in `presets/`, so adding a preset is
 * "drop a file, run `npm run presets:sync`" (the Theme lab does this for you). Keeping it a plain, typed module
 * (instead of a Vite glob) means `tsx` scripts, CI and the site all read presets the same way.
 */
import fs from 'node:fs';
import path from 'node:path';
import { builtinPresets } from './builtin';

export const REGISTRY_FILE = '_registry.ts';

export function presetNames(dir: string): string[] {
  const found = fs.readdirSync(dir).filter((f) => f.endsWith('.ts') && !f.startsWith('_')).map((f) => f.slice(0, -3));
  const builtin = (builtinPresets as readonly string[]).filter((n) => found.includes(n));
  return [...builtin, ...found.filter((n) => !builtin.includes(n)).sort()];
}

const ident = (name: string): string => `p_${name.replace(/-/g, '_')}`;
const keyOf = (name: string): string => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : `'${name}'`);

export function renderRegistry(names: string[]): string {
  return [
    '/**',
    ' * GENERATED by `npm run presets:sync` (the Theme lab runs it after saving). Do not edit by hand.',
    ' * Every file in this folder whose name does not start with "_" is a preset; the file name is its `name`.',
    ' */',
    `import type { Theme } from '../schema';`,
    ...names.map((n) => `import ${ident(n)} from './${n}';`),
    '',
    'export const presets = {',
    ...names.map((n) => `  ${keyOf(n)}: ${ident(n)},`),
    '} satisfies Record<string, Theme>;',
    '',
  ].join('\n');
}

/** Rewrites the registry when it is out of date. With `check`, only reports. Returns true when it differs. */
export function syncRegistry(dir: string, check = false): boolean {
  const file = path.join(dir, REGISTRY_FILE);
  const expected = renderRegistry(presetNames(dir));
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  if (current === expected) return false;
  if (!check) fs.writeFileSync(file, expected);
  return true;
}
